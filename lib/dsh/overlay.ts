
/**
 * Cordis patch overlay for harness runs spawned by LazyChat.
 *
 * Mounts our MCP servers as dsh tools (Streamable HTTP, already running
 * inside this Next.js app), so agents get tool selection through MCP:
 * - `brain` → the Company Brain registry (graph reads + actions)
 * - `lazychat-memory` → workspace + shared memory (recall/store)
 *
 * Written once to DATA_DIR (or ./data) and passed as `--patch` to every run.
 */
import fs from "node:fs";
import path from "node:path";

const OVERLAY_NAME = "lazychat-bridge.cordis.yml";

function dataDir(): string {
  return process.env.DATA_DIR ?? path.resolve(process.cwd(), "data");
}

/** Base URL of this app as seen by spawned processes (same machine). */
function appBaseUrl(): string {
  const port = process.env.PORT ?? "3000";
  return process.env.DSH_BRIDGE_URL ?? `http://127.0.0.1:${port}`;
}

function overlayYaml(base: string): string {
  return `# Generated by LazyChat — default model + MCP tools for harness runs.
- id: agent-default-model
  config:
    provider: sarvam
    model: sarvam-105b
- id: llm-pi-ai
  config:
    providers:
      sarvam:
        displayName: Sarvam
        apiKeyEnv: SARVAM_API_KEY
        api: openai-completions
        baseURL: https://api.sarvam.ai/v1
        models:
          - id: sarvam-105b
            contextWindow: 32768
- insert:
    - id: lazychat-memory-mcp
      name: '@deepseek-ai/dsh-mcp-client'
      config:
        serverName: lazychat_memory
        transport: streamable-http
        url: ${base}/api/dsh/memory/mcp
- insert:
    - id: lazychat-brain-mcp
      name: '@deepseek-ai/dsh-mcp-client'
      config:
        serverName: company_brain
        transport: streamable-http
        url: ${base}/api/brain/mcp
`;
}

/** Write (or refresh) the overlay and return its absolute path. */
export async function writeRunPatch(): Promise<string> {
  const dir = path.join(dataDir(), "dsh");
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, OVERLAY_NAME);
  fs.writeFileSync(file, overlayYaml(appBaseUrl()), "utf8");
  return file;
}
